    // Apple hands the device token to the app delegate, not to the web view.
    // These pass it on to Capacitor, where the Firebase messaging plugin
    // turns it into the Firebase token the server sends to. Without them an
    // iPhone never finished registering for notifications.
    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(name: .capacitorDidRegisterForRemoteNotifications, object: deviceToken)
    }

